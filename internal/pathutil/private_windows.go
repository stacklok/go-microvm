//go:build windows

package pathutil

import (
	"fmt"
	"os"
)

func ensurePrivateDir(path string) error {
	if err := os.MkdirAll(path, 0o700); err != nil {
		return fmt.Errorf("create private directory %s: %w", path, err)
	}
	return nil
}
